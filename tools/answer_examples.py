"""The «Формат ответа для общих политик» section of docs/ADAPTER.md, generated from a real episode.

    python3.11 -m tools.answer_examples            print the section (markdown)
    python3.11 -m tools.answer_examples --check    exit 1 when docs/ADAPTER.md holds another text

A fresh train episode (seed 424242, one error of each type, no secret: reproducible by design, it is
not one of the committed `episodes/`) is generated by `judge_adapter.generate_episode`; the findings
are those of the oracle (`policies/oracle.py`) with a short explanation, so every id, amount and
evidence set in the section is real and scores TP in that episode. Nothing is written anywhere.
"""
from __future__ import annotations

import json
import pathlib
import sys
import tempfile
import warnings

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = 424242
CONFIG = {"errors": {"duplicate_invoice": 1, "allocation_gap": 1, "fx_error": 1, "period_cutoff": 1}}
BEGIN, END = "<!-- answer-examples:begin -->", "<!-- answer-examples:end -->"

NOTES = {
    "duplicate_invoice": (
        "`affected_ids` — `doc_id` обоих счетов-дублей (не `invoice_id`). Сумма — `total_minor` счёта в минимальных "
        "единицах валюты счёта, `currency` — валюта счёта. Доказательства: оба `doc_id` и по одной проводке каждого "
        "счёта (Дт дебиторки или Кт выручки; достаточно одного допустимого набора из четырёх).",
        "Два счёта с одним контрагентом, валютой, итогом и позициями."),
    "allocation_gap": (
        "`affected_ids` — `doc_id` платежа и `doc_id` счёта (не `payment_id`/`invoice_id`). Сумма — `credit_minor` "
        "строки `unallocated` платежа как записано в ledger; `currency` — базовая валюта (`policy.base_currency`), "
        "а не валюта платежа. Доказательства: оба `doc_id`, строка `unallocated` платежа, Дт дебиторки счёта и Кт "
        "дебиторки платежа (последней нет, если платёж не разнесён вовсе: тогда остальные четыре).",
        "Платёж разнесён не полностью: остаток на unallocated, счёт открыт."),
    "fx_error": (
        "`affected_ids` — `doc_id` одного документа в иностранной валюте. Сумма — модуль разницы между отражённой и "
        "правильной суммой в базовой валюте; `currency` — базовая. Доказательства: `doc_id`, проводка документа "
        "(для счёта Дт дебиторки или Кт выручки, для платежа строка `cash`) и ключ курса.",
        "Проводка посчитана по неверному курсу."),
    "period_cutoff": (
        "`affected_ids` — `doc_id` одного счёта вне периода, но проведённого. Сумма — `total_minor` счёта, `currency` "
        "— валюта счёта. Доказательства: `doc_id` и одна из двух проводок счёта.",
        "Счёт датирован вне отчётного периода, но проведён."),
}


def _episode():
    import judge_adapter
    from auditgym.storage import load_episode

    with tempfile.TemporaryDirectory() as directory:
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore", message="generate_episode: no secret", category=RuntimeWarning)
            judge_adapter.generate_episode(SEED, CONFIG, directory)
        return load_episode(directory)


def render() -> str:
    from policies.oracle import Oracle

    episode = _episode()
    episode_id = episode["public"]["manifest"]["episode_id"]
    oracle = Oracle(episode["private"]["truth"])
    oracle.reset({"manifest": {"episode_id": episode_id}})
    found = {f["type"]: f for f in oracle.act({})["findings"]["findings"]}
    base = episode["public"]["policy"]["base_currency"]
    fx_example = _colon(next(i for i in found["fx_error"]["evidence_ids"] if "|" in i))
    out = [BEGIN,
           "Примеры получены из свежего обучающего эпизода (`python3.11 -m tools.answer_examples`, seed "
           f"{SEED}, по одной ошибке каждого типа; это не эпизоды из `episodes/`). Значения настоящие: каждый "
           "вывод засчитывается как TP в своём эпизоде. Базовая валюта эпизода — "
           f"`{base}`; `episode_id` — `{episode_id}`.",
           "",
           "Общие правила:",
           "",
           "- `affected_ids` — `doc_id` документов (таблицы `invoices`, `payments`), а не `invoice_id`/`payment_id`; "
           "в `evidence_ids` к ним добавляются `row_id` строк `ledger` и ключ курса.",
           "- Обязательны все шесть полей вывода и `episode_id` на верхнем уровне; `explanation` — строка до 1000 "
           "символов, пустая допустима (без поля весь submit — неверная структура, −1).",
           "- `claimed_amount_minor` — JSON-целое в минимальных единицах валюты; `currency` — точный код: у "
           "`duplicate_invoice` и `period_cutoff` валюта счёта, у `allocation_gap` и `fx_error` базовая валюта.",
           f"- Ключ курса: `дата:ИСТ:ЦЕЛЬ` (например `{fx_example}`) или `дата|ИСТ|ЦЕЛЬ`; адаптер принимает "
           "обе записи в `evidence_ids`/`affected_ids`. Дата — дата документа в поясе компании, ИСТ — валюта "
           "документа, ЦЕЛЬ — базовая валюта.",
           "- `invoice_id`/`payment_id` — не ID документа для ответа: ни в `affected_ids`, ни в `evidence_ids` они не считаются (ID сравниваются точно; в `evidence_ids` это просто несуществующий ID, то есть FP). Лимиты (30 выводов, 10 ID в `evidence_ids`, 1000 символов) считаются по присланным спискам до любой замены записи ключа курса.",
           ""]
    for kind in ("duplicate_invoice", "allocation_gap", "fx_error", "period_cutoff"):
        finding = dict(found[kind], explanation=NOTES[kind][1])
        finding["evidence_ids"] = [_colon(i) for i in finding["evidence_ids"]]
        out += [f"**{kind}.** {NOTES[kind][0]}", "", "```json", json.dumps(finding, ensure_ascii=False, indent=2),
                "```", ""]
    out += [f"Ключ курса в примере `fx_error` — `{fx_example}`. Весь ответ — JSON-объект "
            '`{"episode_id": "' + episode_id + '", "findings": [ ...выводы... ]}` (п. 14: строка JSON и голый список в адаптере — неверная структура); '
            "порядок выводов и ID в списках значения не имеет.", END]
    return "\n".join(out)


def _colon(identifier: str) -> str:
    parts = identifier.split("|")
    return ":".join(parts) if len(parts) == 3 else identifier


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        doc = (ROOT / "docs" / "ADAPTER.md").read_text(encoding="utf-8")
        if BEGIN not in doc or END not in doc:
            print("docs/ADAPTER.md has no answer-examples block", file=sys.stderr)
            return 1
        held = doc[doc.index(BEGIN):doc.index(END) + len(END)]
        if held != text:
            print("docs/ADAPTER.md is out of date: python3.11 -m tools.answer_examples", file=sys.stderr)
            return 1
        return 0
    if argv:
        print("usage: python3.11 -m tools.answer_examples [--check]", file=sys.stderr)
        return 2
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
